// The visual character folio is a *presentation of the Markdown document*.
// It does not depend on the generator's internal model or change exported bytes.
// Generated and imported QuickSheet .md files take the same rendering path.
import { escapeHtml, markdownToHtml } from './preview.js';

const clean = (value) => String(value ?? '').trim();
const safeClass = (value) => clean(value).toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '');

function collectSections(markdown) {
  const text = String(markdown ?? '').replace(/\r\n/g, '\n');
  const match = text.match(/\n---\s*\n(?=\s*\*Generated by QuickSheet)/);
  const body = match ? text.slice(0, match.index) : text;
  const attribution = match ? text.slice(match.index + match[0].length) : '';
  const chunks = body.split(/^##\s+/m);
  const intro = chunks.shift() ?? '';
  const sections = new Map();
  for (const chunk of chunks) {
    const firstNewline = chunk.indexOf('\n');
    if (firstNewline === -1) continue;
    sections.set(chunk.slice(0, firstNewline).trim(), chunk.slice(firstNewline + 1).trim());
  }
  return { intro, sections, attribution };
}

function subSections(body) {
  const result = [];
  let current = { title: '', content: [] };
  for (const line of clean(body).split('\n')) {
    const heading = line.match(/^###\s+(.+)$/);
    if (heading) {
      if (current.title || current.content.some((text) => text.trim())) result.push({ title: current.title, body: current.content.join('\n').trim() });
      current = { title: heading[1].trim(), content: [] };
    } else {
      current.content.push(line);
    }
  }
  if (current.title || current.content.some((text) => text.trim())) result.push({ title: current.title, body: current.content.join('\n').trim() });
  return result;
}

function rowsFromMarkdown(content) {
  const lines = clean(content).split('\n');
  const start = lines.findIndex((line, index) => line.startsWith('|') && /^\|\s*:?-{3,}/.test(lines[index + 1] ?? ''));
  if (start < 0) return { headers: [], rows: [], remainder: content };
  const cells = (line) => line.trim().replace(/^\||\|$/g, '').split(/(?<!\\)\|/).map((x) => x.replace(/\\\|/g, '|').trim());
  const headers = cells(lines[start]);
  let end = start + 2;
  const rows = [];
  while (end < lines.length && lines[end].startsWith('|')) rows.push(cells(lines[end++]));
  return { headers, rows, remainder: [...lines.slice(0, start), ...lines.slice(end)].join('\n').trim() };
}

function sectionHeading(kicker, title, aside = '') {
  return `<div class="folio-section-heading"><div><span class="folio-kicker">${escapeHtml(kicker)}</span><h3>${escapeHtml(title)}</h3></div>${aside ? `<span class="folio-heading-aside">${escapeHtml(aside)}</span>` : ''}</div>`;
}

function panel(className, kicker, title, content, aside = '') {
  return `<section class="folio-panel ${className}">${sectionHeading(kicker, title, aside)}${content}</section>`;
}

function parseIdentity(intro) {
  const name = intro.match(/^#\s+(.+)$/m)?.[1] ?? 'Unnamed character';
  const concept = intro.match(/^\*([^\n*]+)\*$/m)?.[1] ?? '';
  const level = intro.match(/\*\*Level:\*\*\s*(\d+)(?:\s*\(Tier\s*(\d+)\))?/);
  const cls = intro.match(/\*\*Class:\*\*\s*([^\n|]+)/)?.[1].trim() ?? '';
  const heritage = intro.match(/\*\*Heritage:\*\*\s*([^\n|]+)/)?.[1].trim() ?? '';
  const pronouns = intro.match(/\*\*Pronouns:\*\*\s*([^\n|]+)/)?.[1].trim() ?? '';
  const transformation = intro.match(/\*\*Transformation:\*\*\s*([^\n|]+)/)?.[1].trim() ?? '';
  const [characterClass, ...subclassParts] = cls.split(/\s+-\s+/);
  const [ancestry, ...communityParts] = heritage.split(/\s*\/\s*/);
  return { name, concept, level: level?.[1] ?? '', tier: level?.[2] ?? '',
    characterClass, subclass: subclassParts.join(' - '), ancestry, community: communityParts.join(' / '), transformation, pronouns };
}

function identityMarkup(identity) {
  const bits = [
    ['Class & path', [identity.characterClass, identity.subclass].filter(Boolean).join(' · ')],
    ['Heritage', [identity.ancestry, identity.community].filter(Boolean).join(' / ')],
    ['Transformation', identity.transformation],
    ['Pronouns', identity.pronouns],
  ].filter(([, val]) => val);
  return `<header class="folio-identity">
    <div class="folio-identity-ornament" aria-hidden="true">✦</div>
    <div class="folio-hero-top"><span class="folio-eyebrow">The adventurer's record</span><span class="folio-serial">QUICKSHEET <i>◆</i> SRD 2.0</span></div>
    <div class="folio-hero-main"><div><h2>${escapeHtml(identity.name)}</h2>${identity.concept ? `<p class="folio-concept">${escapeHtml(identity.concept)}</p>` : ''}</div>
    ${identity.level ? `<div class="level-seal"><span>LEVEL</span><strong>${escapeHtml(identity.level)}</strong>${identity.tier ? `<small>TIER ${escapeHtml(identity.tier)}</small>` : ''}</div>` : ''}</div>
    <div class="folio-identity-meta">${bits.map(([label, val]) => `<div class="folio-id-detail"><span>${escapeHtml(label)}</span><strong>${escapeHtml(val)}</strong></div>`).join('')}</div>
  </header>`;
}

function parseGlance(content) {
  const table = rowsFromMarkdown(content);
  const traits = table.headers.map((name, i) => ({ name, value: table.rows[0]?.[i] ?? '—' }));
  const values = new Map();
  for (const match of table.remainder.matchAll(/\*\*([^*]+)\*\*\s*([^|\n]+)/g)) values.set(match[1].toLowerCase(), match[2].trim());
  return { traits, values, remainder: table.remainder };
}

function statNumber(glance, label) {
  return glance.values.get(label.toLowerCase())?.match(/^-?\d+/)?.[0] ?? '—';
}

const resourceMode = {
  hp: 'marked', stress: 'marked', hope: 'available', armor: 'marked',
  rally: 'spent', prayer: 'spent', slayer: 'held', combo: 'marked',
  patron: 'marked', commune: 'rolled', focus: 'held', favor: 'held',
};

function marks(count, filled, kind, label) {
  const total = Math.max(0, Math.min(30, Number(count) || 0));
  const active = Math.max(0, Math.min(total, Number(filled) || 0));
  const mode = resourceMode[kind] || 'marked';
  const buttons = Array.from({ length: total }, (_, i) => {
    const pressed = i < active;
    return `<button type="button" class="folio-track-mark${pressed ? ' is-filled' : ''}" data-resource="${kind}" data-index="${i}" aria-pressed="${pressed}" aria-label="${escapeHtml(label)} slot ${i + 1}: ${pressed ? mode : 'empty'}. Activate to toggle."><span class="visually-hidden">${i + 1}</span></button>`;
  }).join('');
  return `<div class="folio-track folio-track--${kind}" data-track="${kind}" data-label="${escapeHtml(label)}" data-mode="${mode}">${buttons}</div>`;
}

function counter(label, value, kind) {
  if (!value) return '';
  const isHope = kind === 'hope';
  const max = isHope ? value.match(/max\s+(\d+)/i)?.[1] : kind === 'armor' ? value.match(/\((\d+)\s+Armor Slots/i)?.[1] : value.match(/(\d+)\s+slots/i)?.[1];
  const used = isHope ? value.match(/^(\d+)/)?.[1] : value.match(/(\d+)\s+marked/i)?.[1];
  if (!max) return `<div class="folio-counter"><span>${escapeHtml(label)}</span><strong>${escapeHtml(value)}</strong></div>`;
  const count = Math.min(Number(max), Number(used ?? 0));
  const mode = resourceMode[kind];
  return `<div class="folio-counter">
    <div class="folio-counter-top"><span>${escapeHtml(label)}</span><strong data-count-for="${kind}" aria-live="polite">${count} / ${max}</strong></div>
    ${marks(max, count, kind, label)}
    <small data-detail-for="${kind}">${count} ${mode} / ${max} slots</small>
  </div>`;
}

// Feature resources with manual markers: [key, label, At a Glance field, fixed slot count].
// Without a fixed count, the slots come from the dice count (e.g. "3d4"). Favor starts filled to its value.
const FEATURE_TRACKS = [
  ['rally', 'Rally Die', 'rally die', 1],
  ['prayer', 'Prayer dice', 'prayer dice per session', null],
  ['slayer', 'Slayer dice', 'slayer dice (maximum stored)', null],
  ['combo', 'Combo Die', 'combo die', 1],
  ['patron', 'Patron Die', 'patron die', 1],
  ['commune', 'Commune dice', 'commune dice', null],
  ['focus', 'Focus', 'focus', 6],
  ['favor', 'Favor', 'favor', 6],
];
const TRACKED_FIELDS = new Set([...FEATURE_TRACKS.map(([, , field]) => field), 'unstoppable die']);

function specialResources(glance) {
  const values = glance.values;
  const cards = [];
  for (const [key, label, field, fixed] of FEATURE_TRACKS) {
    const value = values.get(field);
    if (!value) continue;
    const die = value.match(/\b(\d*)d(\d+)\b/i);
    const count = fixed ?? (die ? Number(die[1] || 1) : 0);
    const initial = key === 'favor' ? Number(value.match(/^\d+/)?.[0] ?? 0) : 0;
    if (!count || count > 30) continue;
    const mode = resourceMode[key];
    const type = die ? `d${die[2]}` : (key === 'focus' || key === 'favor' ? 'POOL' : '');
    cards.push(`<div class="special-resource-card">
      <div class="special-resource-head"><div><span class="special-resource-label">${escapeHtml(label)}</span><small>${escapeHtml(type)}</small></div><strong data-count-for="${key}" aria-live="polite">${initial} / ${count}</strong></div>
      ${marks(count, initial, key, label)}
      <small class="special-resource-detail" data-detail-for="${key}">${initial} ${mode} / ${count} slots</small>
    </div>`);
  }
  const unstoppable = values.get('unstoppable die');
  if (unstoppable) {
    const max = Math.max(2, Math.min(20, Number(unstoppable.match(/\bd(\d+)/i)?.[1] ?? 4)));
    cards.push(`<div class="special-resource-card special-resource-card--die">
      <div class="special-resource-head"><div><span class="special-resource-label">Unstoppable Die</span><small>d${max} · face value</small></div></div>
      <div class="die-control" data-die="unstoppable" data-max="${max}" data-value="0"><button type="button" data-adjust="-1" aria-label="Decrease Unstoppable Die face">−</button><strong data-die-value aria-live="polite">—</strong><button type="button" data-adjust="1" aria-label="Increase Unstoppable Die face">+</button></div>
      <small class="special-resource-detail">— is inactive; adjust manually</small>
    </div>`);
  }
  return cards.length ? `<div class="special-resources"><h4>Feature resources <span>Manual marks, no dice rolling</span></h4><div class="special-resource-grid">${cards.join('')}</div></div>` : '';
}

function glanceMarkup(glance) {
  const traitMarkup = glance.traits.length ? `<div class="trait-grid">${glance.traits.map(({ name, value }) => `<div class="trait"><span class="trait-label">${escapeHtml(name)}</span><span class="trait-value">${escapeHtml(value)}</span></div>`).join('')}</div>` : markdownToHtml(glance.remainder);
  const damage = glance.values.get('damage thresholds') ?? '';
  const major = damage.match(/Major\s+(\d+)/i)?.[1] ?? '—';
  const severe = damage.match(/Severe\s+(\d+)/i)?.[1] ?? '—';
  const statTiles = [ ['Evasion', statNumber(glance, 'Evasion')], ['Proficiency', statNumber(glance, 'Proficiency')], ['Armor score', statNumber(glance, 'Armor Score')] ];
  const extraResources = [...glance.values].filter(([name]) => !['evasion', 'proficiency', 'spellcast trait', 'hp', 'stress', 'hope', 'armor score', 'damage thresholds'].includes(name) && !TRACKED_FIELDS.has(name));
  const totals = `<div class="quick-stat-grid">${statTiles.map(([label, value]) => `<div class="quick-stat"><span>${escapeHtml(label)}</span><strong>${escapeHtml(value)}</strong></div>`).join('')}</div>`;
  const tracks = `<div class="resource-stack">${counter('Hit points', glance.values.get('hp'), 'hp')}${counter('Stress', glance.values.get('stress'), 'stress')}${counter('Hope', glance.values.get('hope'), 'hope')}${counter('Armor slots', glance.values.get('armor score'), 'armor')}</div>`;
  const thresholds = `<div class="thresholds"><div><span>Major damage</span><strong>${escapeHtml(major)}</strong></div><span class="thresholds-rule" aria-hidden="true">/</span><div><span>Severe damage</span><strong>${escapeHtml(severe)}</strong></div></div>`;
  const extra = [glance.values.get('spellcast trait') ? `<div class="spellcast"><span>Spellcast trait</span><strong>${escapeHtml(glance.values.get('spellcast trait'))}</strong></div>` : '', ...extraResources.map(([name, val]) => `<div class="spellcast"><span>${escapeHtml(name)}</span><strong>${escapeHtml(val)}</strong></div>`) ].filter(Boolean).join('');
  return { traitMarkup, vitals: totals + tracks + thresholds + specialResources(glance) + extra };
}

function experiencesMarkup(body) {
  const lines = body.split('\n').filter((line) => line.startsWith('- '));
  if (!lines.length) return markdownToHtml(body);
  return `<div class="experiences-list">${lines.map((line) => {
    const match = line.slice(2).match(/^\*\*(.+?)\*\*\s+([+-]\d+)(.*)$/);
    if (!match) return `<div class="experience-entry">${markdownToHtml(line)}</div>`;
    return `<div class="experience-entry"><div><strong>${escapeHtml(match[1])}</strong>${match[3] ? `<small>${escapeHtml(match[3].trim())}</small>` : ''}</div><span class="experience-mod">${escapeHtml(match[2])}</span></div>`;
  }).join('')}</div>`;
}

function weaponsMarkup(body) {
  const table = rowsFromMarkdown(body);
  if (!table.rows.length) return `<div class="prose">${markdownToHtml(body)}</div>`;
  const cards = table.rows.map((cells) => {
    const [slot, weapon, attack, range, damage, burden] = cells;
    return `<div class="weapon-card"><div class="weapon-card-top"><span>${escapeHtml(slot)}</span><span class="weapon-damage">${escapeHtml(damage)}</span></div>
      <h5>${escapeHtml(weapon)}</h5><div class="weapon-details"><span><small>Attack</small>${escapeHtml(attack)}</span><span><small>Range</small>${escapeHtml(range)}</span><span><small>Burden</small>${escapeHtml(burden)}</span></div></div>`;
  });
  return `<div class="weapons-list">${cards.join('')}</div>${table.remainder ? `<div class="weapon-notes prose">${markdownToHtml(table.remainder)}</div>` : ''}`;
}

function combatMarkup(body) {
  const blocks = subSections(body);
  const chunks = [];
  for (const block of blocks) {
    if (!block.title) { chunks.push(`<div class="gear-note prose">${markdownToHtml(block.body)}</div>`); continue; }
    const contents = block.title === 'Weapons' ? weaponsMarkup(block.body) : `<div class="prose">${markdownToHtml(block.body)}</div>`;
    chunks.push(`<section class="equipment-section"><h4>${escapeHtml(block.title)}</h4>${contents}</section>`);
  }
  return chunks.join('');
}

function featureCards(body, family) {
  // The generated document uses **Feature Name.** at the start of each
  // feature's first paragraph. A card owns any following paragraphs / lists.
  const paragraphs = clean(body).split(/\n{2,}/);
  const cards = [];
  let current = null;
  for (const part of paragraphs) {
    const match = part.match(/^\*\*([^*\n]+?)\.\*\*\s*([\s\S]*)$/);
    if (match) {
      if (current) cards.push(current);
      current = { title: match[1], body: match[2] };
    } else if (current) {
      current.body += `\n\n${part}`;
    } else if (part.trim()) {
      cards.push({ title: '', body: part });
    }
  }
  if (current) cards.push(current);
  return `<div class="feature-card-grid">${cards.map(({ title, body: text }) => `<article class="feature-card feature-card--${safeClass(family)}">
    <div class="feature-card-top"><span>${escapeHtml(family)}</span><span aria-hidden="true">✧</span></div>
    ${title ? `<h5>${escapeHtml(title)}</h5>` : ''}
    <div class="prose">${markdownToHtml(text)}</div>
  </article>`).join('')}</div>`;
}

function featureBlocks(body) {
  return subSections(body).map((block) => {
    if (!block.title) return `<div class="prose">${markdownToHtml(block.body)}</div>`;
    const prefix = block.title.split(':')[0];
    const isLong = /beastform|companion|martial stances/i.test(block.title);
    const title = block.title.includes(':') ? block.title.slice(block.title.indexOf(':') + 1).trim() : block.title;
    const content = isLong ? `<div class="feature-reference prose">${markdownToHtml(block.body)}</div>` : featureCards(block.body, prefix);
    return { title: block.title, prefix, long: isLong, html: `<section class="feature-group feature-group--${safeClass(prefix)}"><div class="feature-group-head"><span class="feature-group-rule"></span><span>${escapeHtml(prefix)}</span></div><h4>${escapeHtml(title)}</h4>${content}</section>` };
  });
}

function domainCardMarkup(block) {
  const lines = block.body.split('\n');
  const details = lines.find((line) => /^\*[^*]+\*.*$/.test(line.trim())) ?? '';
  const info = details.match(/^\*([^*]+?)\s+(\d+)\s*-\s*([^-*]+?)\s*-\s*Recall\s+(\d+)\*(.*)$/);
  const content = info ? block.body.replace(details, '').trim() : block.body;
  const domain = info?.[1] ?? 'Domain';
  const level = info?.[2] ?? '';
  const type = info?.[3] ?? '';
  const recall = info?.[4] ?? '';
  return `<article class="domain-card domain--${safeClass(domain)}">
    <div class="domain-topline"><span class="domain-name">${escapeHtml(domain)}</span>${level ? `<span class="domain-level">LVL ${escapeHtml(level)}</span>` : ''}</div>
    <h4>${escapeHtml(block.title)}</h4><div class="domain-stats"><span>${escapeHtml(type)}</span>${recall ? `<span>RECALL ${escapeHtml(recall)}</span>` : ''}</div>
    <div class="domain-description prose">${markdownToHtml(content)}</div>
  </article>`;
}

function domainsMarkup(body, vault = false) {
  const blocks = subSections(body);
  const cardBlocks = blocks.filter((b) => b.title);
  if (!cardBlocks.length) return `<div class="prose">${markdownToHtml(body)}</div>`;
  const cards = `<div class="domain-grid">${cardBlocks.map(domainCardMarkup).join('')}</div>`;
  if (vault) return `<details class="vault-fold"><summary><span>View ${cardBlocks.length} cards in the vault</span><span class="vault-chevron" aria-hidden="true"></span></summary>${cards}</details>`;
  return cards;
}

function storyMarkup(body) {
  const questionStart = body.indexOf('**Background question:**');
  const main = questionStart >= 0 ? body.slice(0, questionStart) : body;
  const relation = questionStart >= 0 ? body.slice(questionStart) : '';
  return `<div class="story-columns"><div class="story-prose prose">${markdownToHtml(main)}</div>${relation ? `<aside class="connections prose"><span class="folio-kicker">At the table</span>${markdownToHtml(relation)}</aside>` : ''}</div>`;
}

function historyMarkup(body) {
  const lines = body.split('\n').filter((line) => line.trim().startsWith('- '));
  if (!lines.length) return markdownToHtml(body);
  return `<div class="history-list">${lines.map((line) => {
    const match = line.trim().match(/^-\s+\*\*(Level\s+\d+(?:\s+\(Tier\s+\d+\))?):\*\*\s*(.*)$/);
    if (!match) return `<div class="history-entry prose">${markdownToHtml(line)}</div>`;
    return `<div class="history-entry"><span class="history-dot" aria-hidden="true"></span><h4>${escapeHtml(match[1])}</h4><div class="prose">${markdownToHtml(match[2])}</div></div>`;
  }).join('')}</div>`;
}

export function sheetNameFromMarkdown(markdown) {
  return parseIdentity(collectSections(markdown).intro).name;
}

// Import-safe fallback for other Markdown documents. All user-controlled text
// goes through the escaping Markdown renderer; no raw HTML is inserted.
export function renderCharacterSheet(markdown) {
  const { intro, sections, attribution } = collectSections(markdown);
  const glanceBody = sections.get('At a Glance');
  if (!glanceBody || !/^#\s+.+$/m.test(intro)) {
    return `<div class="folio-fallback"><div class="folio-fallback-header"><span class="folio-kicker">Markdown document</span><h2>Document preview</h2></div><div class="prose">${markdownToHtml(markdown)}</div></div>`;
  }
  const identity = parseIdentity(intro);
  const glance = glanceMarkup(parseGlance(glanceBody));
  const features = featureBlocks(sections.get('Features') ?? '');
  const mainFeatures = features.filter((f) => typeof f === 'string' || !f.long);
  const longFeatures = features.filter((f) => typeof f !== 'string' && f.long);
  const hook = sections.get('Character Hook');
  const history = sections.get('Advancement History');
  const vault = sections.get('Domain Cards - Vault');
  const cards = sections.get('Domain Cards - Active Loadout');

  return `<div class="folio-page">
    ${identityMarkup(identity)}
    ${panel('traits-panel', '01 / Attributes', 'Core traits', glance.traitMarkup, 'The six traits')}
    <div class="folio-columns">
      <div class="folio-column folio-column--left">
        ${panel('vitals-panel', '02 / In the field', 'Vitals & defenses', glance.vitals)}
        ${sections.has('Experiences') ? panel('experience-panel', '03 / Expertise', 'Experiences', experiencesMarkup(sections.get('Experiences'))) : ''}
        ${mainFeatures.length ? panel('features-panel', '04 / Character abilities', 'Features & heritage', mainFeatures.map((f) => typeof f === 'string' ? f : f.html).join('')) : ''}
      </div>
      <div class="folio-column folio-column--right">
        ${sections.has('Combat & Gear') ? panel('combat-panel', '05 / Equipment', 'Arsenal & inventory', combatMarkup(sections.get('Combat & Gear'))) : ''}
        ${cards ? panel('domain-panel', '06 / Powers', 'Domain cards', domainsMarkup(cards), 'Active loadout') : ''}
        ${vault ? panel('vault-panel', '07 / Archive', 'Card vault', domainsMarkup(vault, true)) : ''}
      </div>
    </div>
    ${longFeatures.length ? panel('wide-features-panel', 'Reference / Special features', 'Forms & companions', longFeatures.map((f) => f.html).join('')) : ''}
    ${hook ? panel('story-panel', '08 / The person behind the numbers', 'Character story', storyMarkup(hook)) : ''}
    ${history ? panel('history-panel', '09 / The journey so far', 'Advancement history', historyMarkup(history)) : ''}
    ${panel('notes-panel', '10 / Your chronicle', 'Session notes', `<label class="notes-label" for="folio-session-notes">Your notes, discoveries & reminders</label><textarea id="folio-session-notes" data-session-notes rows="7" maxlength="30000" placeholder="What happened in your last session? Who did you meet? What must you remember?"></textarea><p class="notes-hint">Notes and marked slots are saved in your downloaded HTML or Markdown file. To keep future changes, download a new copy.</p>`)}
    ${attribution ? `<details class="folio-attribution"><summary>Source notes & attribution</summary><div class="prose">${markdownToHtml(attribution)}</div></details>` : ''}
    <div class="folio-endmark" aria-hidden="true">✧ <span>QUICKSHEET • THE STORY IS YOURS</span> ✧</div>
  </div>`;
}
