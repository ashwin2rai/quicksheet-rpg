/* QuickSheet's tiny shared folio runtime. Classic script by design: it runs on
   GitHub Pages and can be embedded verbatim in a standalone file:// HTML sheet.
   No dependencies, network calls, dice rolls, or rules automation. */
(function (global) {
  'use strict';

  const RESOURCE_LABELS = Object.freeze({
    hp: 'Hit points', stress: 'Stress', hope: 'Hope', armor: 'Armor slots',
    rally: 'Rally Die', prayer: 'Prayer dice', slayer: 'Slayer dice',
    combo: 'Combo Die', unstoppable: 'Unstoppable Die',
    patron: 'Patron Die', commune: 'Commune dice', focus: 'Focus', favor: 'Favor',
  });
  const LABEL_TO_KEY = Object.fromEntries(Object.entries(RESOURCE_LABELS).map(([key, label]) => [label.toLowerCase(), key]));
  const FOOTER = /\n---\s*\n(?=\s*\*Generated by QuickSheet)/g;
  function findFooter(source) {
    // Use the last attribution footer, not a lookalike string inside user notes.
    const matches = [...source.matchAll(FOOTER)];
    return matches.at(-1) ?? null;
  }

  // Annotations live at the end of the body, immediately BEFORE the required
  // attribution footer. The original model/statistics are never rewritten.
  function parseMarkdown(markdown) {
    const source = String(markdown ?? '').replace(/\r\n/g, '\n');
    const footerMatch = findFooter(source);
    const footer = footerMatch ? source.slice(footerMatch.index) : '';
    let body = footerMatch ? source.slice(0, footerMatch.index) : source;
    let notes = '';
    let trackingEnabled = false;
    const resources = {};

    const notesMatch = /\n## Notes[ \t]*\n/.exec(body);
    if (notesMatch) {
      notes = body.slice(notesMatch.index + notesMatch[0].length).replace(/^\n/, '').replace(/\n+$/, '');
      body = body.slice(0, notesMatch.index);
    }
    const trackingMatch = /\n## Session Tracking[ \t]*\n/.exec(body);
    if (trackingMatch) {
      const text = body.slice(trackingMatch.index + trackingMatch[0].length);
      for (const line of text.split('\n')) {
        const match = /^- \*\*([^*]+):\*\*\s*(.*)$/.exec(line.trim());
        if (!match) continue;
        const key = LABEL_TO_KEY[match[1].toLowerCase()];
        if (!key) continue;
        if (key === 'unstoppable') {
          const face = Number.parseInt(match[2], 10);
          if (Number.isInteger(face) && face >= 0 && face <= 20) resources[key] = face;
        } else {
          const symbols = match[2].match(/[●○]/g);
          if (symbols && symbols.length <= 30) resources[key] = symbols.map((symbol) => symbol === '●');
        }
      }
      trackingEnabled = true;
      body = body.slice(0, trackingMatch.index);
    }
    const baseMarkdown = (trackingMatch || notesMatch) ? `${body.replace(/\s+$/, '')}${footer ? `\n\n${footer.trimStart()}` : '\n'}` : source;
    return { baseMarkdown, notes, resources, trackingEnabled };
  }

  function composeMarkdown(base, session = {}) {
    const cleanBase = parseMarkdown(base).baseMarkdown;
    const notes = String(session.notes ?? '');
    const resources = session.resources ?? {};
    const tracking = Boolean(session.trackingEnabled);
    if (!tracking && !notes.trim()) return cleanBase;

    const footerMatch = findFooter(cleanBase);
    const main = footerMatch ? cleanBase.slice(0, footerMatch.index).replace(/\s+$/, '') : cleanBase.replace(/\s+$/, '');
    const footer = footerMatch ? cleanBase.slice(footerMatch.index).trimStart() : '';
    const sections = [];
    if (tracking) {
      const lines = [
        '## Session Tracking', '',
        '*Display-only marks; these do not change generated character rules or statistics.*', '',
      ];
      for (const [key, label] of Object.entries(RESOURCE_LABELS)) {
        const value = resources[key];
        if (key === 'unstoppable' && Number.isInteger(value)) {
          lines.push(`- **${label}:** ${value} (die face; 0 = inactive)`);
        } else if (Array.isArray(value) && value.length > 0 && value.length <= 30) {
          const checked = value.filter(Boolean).length;
          const mode = key === 'hope' ? 'available' : ['slayer', 'focus', 'favor'].includes(key) ? 'held' : ['rally', 'prayer'].includes(key) ? 'spent' : key === 'commune' ? 'rolled' : 'marked';
          lines.push(`- **${label}:** ${value.map((on) => on ? '●' : '○').join(' ')} (${checked}/${value.length} ${mode})`);
        }
      }
      sections.push(lines.join('\n'));
    }
    if (notes.trim()) sections.push(`## Notes\n\n${notes.replace(/\n+$/, '')}`);
    return `${main}\n\n${sections.join('\n\n')}\n\n${footer}`.replace(/\n+$/, '\n');
  }

  function mount(root, { resources = {}, notes = '', trackingEnabled = false, onChange = () => {} } = {}) {
    let markedOnce = Boolean(trackingEnabled);
    const textarea = root.querySelector('[data-session-notes]');
    if (textarea) textarea.value = String(notes);

    function reflect(resource) {
      const track = root.querySelector(`[data-track="${resource}"]`);
      if (!track) return;
      const slots = [...track.querySelectorAll('button[data-index]')];
      const count = slots.filter((slot) => slot.getAttribute('aria-pressed') === 'true').length;
      const mode = track.dataset.mode || 'marked';
      const total = slots.length;
      const output = root.querySelector(`[data-count-for="${resource}"]`);
      const detail = root.querySelector(`[data-detail-for="${resource}"]`);
      if (output) output.textContent = `${count} / ${total}`;
      if (detail) detail.textContent = `${count} ${mode} / ${total} ${total === 1 ? 'slot' : 'slots'}`;
      for (const slot of slots) {
        const active = slot.getAttribute('aria-pressed') === 'true';
        slot.classList.toggle('is-filled', active);
        slot.setAttribute('aria-label', `${track.dataset.label || resource} slot ${Number(slot.dataset.index) + 1}: ${active ? mode : 'empty'}. Activate to toggle.`);
      }
    }

    for (const track of root.querySelectorAll('[data-track]')) {
      const values = resources[track.dataset.track];
      for (const slot of track.querySelectorAll('button[data-index]')) {
        if (Array.isArray(values) && Number(slot.dataset.index) < values.length) {
          slot.setAttribute('aria-pressed', String(Boolean(values[Number(slot.dataset.index)])));
        }
      }
      reflect(track.dataset.track);
    }

    const die = root.querySelector('[data-die="unstoppable"]');
    if (die) {
      const face = Number(resources.unstoppable);
      const max = Number(die.dataset.max);
      die.dataset.value = String(Number.isInteger(face) && face >= 0 && face <= max ? face : 0);
      reflectDie();
    }
    function reflectDie() {
      if (!die) return;
      const value = Number(die.dataset.value);
      const output = die.querySelector('[data-die-value]');
      if (output) output.textContent = value ? String(value) : '—';
      const minus = die.querySelector('[data-adjust="-1"]');
      const plus = die.querySelector('[data-adjust="1"]');
      if (minus) minus.disabled = value <= 0;
      if (plus) plus.disabled = value >= Number(die.dataset.max);
      die.setAttribute('aria-label', `Unstoppable Die: ${value ? `face ${value}` : 'inactive'}`);
    }

    function snapshot() {
      const current = {};
      for (const track of root.querySelectorAll('[data-track]')) {
        current[track.dataset.track] = [...track.querySelectorAll('button[data-index]')].map((slot) => slot.getAttribute('aria-pressed') === 'true');
      }
      if (die) current.unstoppable = Number(die.dataset.value);
      return { notes: textarea?.value ?? '', resources: current, trackingEnabled: markedOnce };
    }
    function handleClick(event) {
      if (!(event.target instanceof Element)) return;
      const slot = event.target.closest('button[data-resource][data-index]');
      if (slot && root.contains(slot)) {
        slot.setAttribute('aria-pressed', String(slot.getAttribute('aria-pressed') !== 'true'));
        reflect(slot.dataset.resource);
        markedOnce = true;
        onChange(snapshot());
        return;
      }
      const adjust = event.target.closest('button[data-adjust]');
      if (adjust && die && die.contains(adjust)) {
        const current = Number(die.dataset.value);
        die.dataset.value = String(Math.max(0, Math.min(Number(die.dataset.max), current + Number(adjust.dataset.adjust))));
        reflectDie();
        markedOnce = true;
        onChange(snapshot());
      }
    }
    function handleInput(event) {
      if (event.target === textarea) onChange(snapshot());
    }
    root.addEventListener('click', handleClick);
    root.addEventListener('input', handleInput);
    return {
      snapshot,
      destroy() { root.removeEventListener('click', handleClick); root.removeEventListener('input', handleInput); },
    };
  }

  // Shared by the generator page and standalone sheets.
  function applyTheme(button, mode) {
    const dark = mode === 'dark';
    document.documentElement.dataset.theme = dark ? 'dark' : 'light';
    button.setAttribute('aria-pressed', String(dark));
    button.setAttribute('aria-label', `Switch to ${dark ? 'light' : 'dark'} mode`);
    button.querySelector('[data-theme-label]').textContent = dark ? 'Light mode' : 'Dark mode';
    button.querySelector('[data-theme-symbol]').textContent = dark ? '☼' : '☾';
  }

  function download(content, filename, mimeType) {
    const url = URL.createObjectURL(new Blob([content], { type: mimeType }));
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    document.body.append(link);
    link.click();
    link.remove();
    setTimeout(() => URL.revokeObjectURL(url), 5000);
  }

  global.QuickSheetFolio = Object.freeze({ parseMarkdown, composeMarkdown, mount, applyTheme, download });
})(typeof window === 'undefined' ? globalThis : window);
