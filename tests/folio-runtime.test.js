import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { renderCharacterSheet } from '../src/sheet-view.js';
import { buildHtmlDownload } from '../src/sheet-file.js';
import '../src/folio-runtime.js';

const runtime = globalThis.QuickSheetFolio;
const sample = (name) => readFileSync(new URL(`snapshots/${name}`, import.meta.url), 'utf8');
const text = (name) => readFileSync(new URL(`../${name}`, import.meta.url), 'utf8');

test('clean Markdown remains byte-identical until a session edit', () => {
  const md = sample('troubadour.md');
  const parsed = runtime.parseMarkdown(md);
  assert.equal(parsed.baseMarkdown, md);
  assert.equal(runtime.composeMarkdown(md, { notes: '', resources: {}, trackingEnabled: false }), md);
});

test('notes, irregular slot marks and a die face survive Markdown round trips', () => {
  const md = sample('stalwart.md');
  const session = {
    notes: 'Met Alina at the inn.\n## A literal heading\n\n- A secret symbol',
    trackingEnabled: true,
    resources: { hp: [true, false, true, false, false], hope: [true, true, false, false, false, true],
      armor: [false, true, false], unstoppable: 3 },
  };
  const exportMd = runtime.composeMarkdown(md, session);
  const parsed = runtime.parseMarkdown(exportMd);
  assert.equal(parsed.baseMarkdown, md);
  assert.equal(parsed.notes, session.notes);
  assert.deepEqual(parsed.resources.hp, session.resources.hp);
  assert.deepEqual(parsed.resources.hope, session.resources.hope);
  assert.deepEqual(parsed.resources.armor, session.resources.armor);
  assert.equal(parsed.resources.unstoppable, 3);
  assert.equal(parsed.trackingEnabled, true);
  assert.ok(exportMd.indexOf('## Notes') < exportMd.indexOf('Generated by QuickSheet'));
  assert.equal(runtime.composeMarkdown(exportMd, session), exportMd);
});

test('the new folio creates individual heritage/class cards, buttons, feature dice and notes', () => {
  const html = renderCharacterSheet(sample('troubadour.md'));
  assert.match(html, /class="feature-card feature-card--ancestry"/);
  assert.match(html, /class="feature-card feature-card--community"/);
  assert.match(html, /class="feature-card feature-card--class"/);
  assert.match(html, /class="feature-card feature-card--subclass"/);
  assert.match(html, /data-track="hp"/);
  assert.match(html, /data-track="hope"/);
  assert.match(html, /data-track="rally"/);
  assert.match(html, /data-session-notes/);
  assert.equal((html.match(/data-resource="hp"/g) ?? []).length, 5);
  const warlock = renderCharacterSheet(sample('hf-pact-of-the-endless.md'));
  assert.match(warlock, /data-track="patron"/);
  assert.match(warlock, /data-track="favor"/);
  const guardian = renderCharacterSheet(sample('stalwart.md'));
  assert.match(guardian, /data-die="unstoppable"/);
  const witch = renderCharacterSheet(sample('hf-hedge.md'));
  assert.match(witch, /data-track="commune"/);
});

test('standalone export inlines stylesheet, the runtime and escaped content', () => {
  const markdown = sample('troubadour.md');
  const file = buildHtmlDownload({
    baseMarkdown: markdown, character: { flavor: { name: 'Alina <script>' }, seed: 'abc' },
    session: { notes: '</script><img onerror=alert(1)>', resources: { hp: [true, false] }, trackingEnabled: true },
    stylesheet: text('styles.css'), runtime: text('src/folio-runtime.js'), bootstrap: text('src/standalone-init.js'), theme: 'dark',
  });
  assert.match(file.filename, /^quicksheet-/);
  assert.match(file.filename, /\.html$/);
  assert.equal(file.mimeType, 'text/html;charset=utf-8');
  assert.match(file.content, /<html lang="en" data-theme="dark">/);
  assert.match(file.content, /data-session-notes/);
  assert.match(file.content, /id="portable-save-html"/);
  assert.match(file.content, /window\.QuickSheetFolio|global\.QuickSheetFolio/);
  assert.doesNotMatch(file.content, /<script src=|<link rel="stylesheet"/);
  assert.doesNotMatch(file.content, /<title>Alina <script>/);
  assert.doesNotMatch(file.content, /<img onerror=/);
  assert.ok(file.content.includes('\\u003c/script\\u003e'));
});
